-- 粒度：一快照日期 × 项目一行
CREATE TABLE `fact_project_snapshot` (
    `snapshot_date_id` INT NOT NULL COMMENT '风险状态观察日期，联合主键的一部分；关联 dim_date.date_id。',
    `project_id` INT NOT NULL COMMENT '联合主键另一部分，观察项目；关联 dim_project.project_id。',
    `business_unit_id` INT NOT NULL COMMENT '快照时项目所属经营单元；关联 dim_business_unit.business_unit_id。',
    `industry_id` INT NOT NULL COMMENT '快照时项目客户行业；关联 dim_industry.industry_id。',
    `project_stage` VARCHAR(20) NOT NULL COMMENT '商机、方案、投标、商务、签约、交付、完成。',
    `risk_level` VARCHAR(20) NOT NULL COMMENT '项目整体风险等级：低风险、中风险、高风险。',
    `competition_risk` VARCHAR(20) NOT NULL COMMENT '竞争风险等级。',
    `signing_risk` VARCHAR(20) NOT NULL COMMENT '合同签订风险等级。',
    `delivery_risk` VARCHAR(20) NOT NULL COMMENT '供应与交付风险等级。',
    `is_active` TINYINT NOT NULL COMMENT '是否仍在跟进，1 是；完成/关闭项目为 0，默认当前风险统计排除。',
    `risk_description` VARCHAR(255) NOT NULL COMMENT '项目进展及风险说明，不据此生成无数据依据的预测。',
    PRIMARY KEY (`snapshot_date_id`, `project_id`),
    FOREIGN KEY (`snapshot_date_id`) REFERENCES `dim_date` (`date_id`),
    FOREIGN KEY (`project_id`) REFERENCES `dim_project` (`project_id`),
    FOREIGN KEY (`business_unit_id`) REFERENCES `dim_business_unit` (`business_unit_id`),
    FOREIGN KEY (`industry_id`) REFERENCES `dim_industry` (`industry_id`),
    CHECK (is_active IN (0, 1)),
    CHECK (risk_level IN ('低风险', '中风险', '高风险')),
    CHECK (competition_risk IN ('低风险', '中风险', '高风险')),
    CHECK (signing_risk IN ('低风险', '中风险', '高风险')),
    CHECK (delivery_risk IN ('低风险', '中风险', '高风险'))
) ENGINE=InnoDB COMMENT='PPL 项目阶段与风险快照。联合主键 snapshot_date_id/project_id。快照不是事件流水，同一项目多个快照不能累加。当前风险须先取每个项目最近一条快照，再筛选 is_active=1 和风险等级。最新演示快照 2026-05-31。';

