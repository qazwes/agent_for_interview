-- 粒度：一自然日一行
CREATE TABLE `dim_date` (
    `date_id` INT NOT NULL COMMENT '日期编码 YYYYMMDD。',
    `calendar_date` DATE NOT NULL COMMENT '自然日期。',
    `year` SMALLINT NOT NULL COMMENT '自然年。年度目标以 target_year 直接关联此年份，不按每一天连接目标。',
    `quarter` TINYINT NOT NULL COMMENT '季度，1 至 4。',
    `month` TINYINT NOT NULL COMMENT '月份，1 至 12。',
    `day` TINYINT NOT NULL COMMENT '日，1 至 31。',
